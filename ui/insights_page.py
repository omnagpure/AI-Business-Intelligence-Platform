log = get_logger("ui.insights")
STEP_LABEL = {"forecast": "Forecast", "anomalies": "Anomalies", "segmentation": "Segments", "drivers": "Drivers"}
MAX_TOP = 3
_SEV = {"high": ("High priority", "bad"), "medium": ("Medium priority", "warn"), "low": ("Low priority", "flat"),
        "info": ("For information", "flat")}
_KIND_TONE = {"risk": "bad", "opportunity": "good", "pattern": "info", "data": "flat"}
_KIND_ORDER = ("risk", "opportunity", "pattern", "data")
_FILTERS = {"all": "All", "risk": "Needs attention", "opportunity": "Opportunities", "pattern": "Patterns", "data": "Data notes"}


def _advanced(df, profile, model) -> tuple[dict, list[tuple[str, str]], list[str]]:
    """Run the four advanced analyses, one named step each. Each is cached and fails on its own.
    Returns (results, [(analysis, why it could not run)], [analyses that reused your own page settings])."""
    sources = advanced_sources(df, profile, model)
    mine = user_runs()                                   # settings the user chose on the analysis pages win over defaults
    got, why, reused = {}, [], []
    with ProgressBar("Reading your data", numbered=True) as bar:
        run = StepRunner(len(PAGE_NAMES), bar)
        for name in PAGE_NAMES:
            label = STEP_LABEL[name]
            if name in mine:
                run.reuse(label, f"your result from the {PAGE_NAMES[name]} page")
                got[name] = mine[name]
                reused.append(name)
                continue
            inner = lambda i, n, m, lb=label: bar(run.finished, run.total, f"{lb}: {m}")        # noqa: E731
            ok, payload, reason = run.run_status(label, lambda n=name, f=inner: sources[n](f))
            if ok:
                got[name] = payload
            else:
                why.append((name, reason))
        run.done()
    return got, why, reused


def render_insights_page() -> None:
    result = state.get_result()
    if result is None:
        page_title("Insights", "What your data says, why it matters and what to do.")
        no_dataset_notice()
        return
    ds = result.dataset
    page_title("Insights", "What your data says, why it matters and what to do")
    try:
        df, profile, model = state.get_analysis_df(), state.get_analysis_profile(), state.get_semantic_model()
    except Exception:
        log.exception("Insight inputs unavailable")
        st.error("The dataset could not be prepared for analysis. Check the Data quality and Column roles pages.")
        return
    if df is None or profile is None or model is None or len(df) == 0:
        empty_state("Nothing to analyse", "The active dataset has no rows.")
        return
    dom = model.domain.domain
    meta_line([ds.filename + (" (synthetic sample)" if ds.is_sample else ""), f"{len(df):,} rows"],
              badge(DOMAIN_LABELS.get(dom, dom), "accent" if model.is_supply_chain else "neutral"))

    status, kpis = kpi_source(df, model, failure="The KPIs could not be calculated.")()
    if status != "ok":
        st.warning(str(kpis))
        kpis = None
    fstatus, findings = findings_source(df, model)()
    findings = findings if fstatus == "ok" else None
    hint = describe_estimate("insights", len(df))
    if hint:
        st.caption(hint)
    adv, unavailable, reused = _advanced(df, profile, model)

    report = generate_insights(InsightInputs(kpis=kpis, profile=profile, findings=findings, unavailable=tuple(unavailable), **adv),
                               DEFAULT_INSIGHTS)
    _show(report, _shift_text(df, model), unavailable, reused)


def _shift_text(df, model) -> str:
    """The Dashboard's data-shape check on monthly totals (same cache entry), or ""."""
    try:
        date_col = primary_date_column(df, model)
        order = _order_id(_Ctx(df, model, DEFAULT_ANALYTICS, DataFilter()))
        return cached("data_shifts", (date_col, order, "M"), lambda: describe_shifts(detect_shifts(df, date_col, order, "M")))
    except Exception:
        log.exception("Data-shift check failed")
        return ""


