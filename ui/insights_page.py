def _summary(items: list[tuple[Insight, Plan]]) -> str:
    if not items:
        return ("Nothing in this data crossed a threshold: no risks, unusual patterns or data problems were found. That is a "
                "result, not an error. The thresholds are listed under each finding when there is one.")
    n = {k: sum(1 for _, p in items if p.kind == k) for k in _KIND_ORDER}
    high = [i for i, p in items if i.severity == "high" and p.kind in ("risk", "data")]
    parts = []
    if n["risk"]:
        parts.append(f"{n['risk']} {'thing needs' if n['risk'] == 1 else 'things need'} attention")
    if n["opportunity"]:
        parts.append(f"{n['opportunity']} {'opportunity' if n['opportunity'] == 1 else 'opportunities'}")
    if n["pattern"]:
        parts.append(f"{n['pattern']} {'pattern' if n['pattern'] == 1 else 'patterns'} worth knowing")
    if n["data"]:
        parts.append(f"{n['data']} data {'note' if n['data'] == 1 else 'notes'}")
    text = f"We found {len(items)} findings in your data: " + (", ".join(parts[:-1]) + " and " + parts[-1] if len(parts) > 1 else parts[0]) + "."
    first = items[0][0]
    if high:
        text += f" Start here: {high[0].title}."
    elif first.severity != "info":
        text += f" The most important: {first.title}."
    else:
        text += " None of them is urgent."
    return text


def _show(report, shift: str, unavailable: list[tuple[str, str]], reused: list[str]) -> None:
    items = [(i, plan(i)) for i in report.insights]

    lede(_summary(items))
    if shift:
        callout("Data check", shift, "warn")

    n = {k: [i for i, p in items if p.kind == k] for k in _KIND_ORDER}
    hi = lambda xs: sum(1 for i in xs if i.severity == "high")                     # noqa: E731
    stat_cards([
        {"label": "Needs attention", "value": str(len(n["risk"])),
         "chip": (f"{hi(n['risk'])} high", "bad") if hi(n["risk"]) else ("none high", "flat"),
         "foot": "Risks and problems, most urgent first."},
        {"label": "Opportunities", "value": str(len(n["opportunity"])), "chip": ("to act on", "good") if n["opportunity"] else None,
         "foot": "Growth, levers and groups worth more attention."},
        {"label": "Patterns", "value": str(len(n["pattern"])), "foot": "Useful facts for planning; nothing is wrong."},
        {"label": "Data notes", "value": str(len(n["data"])),
         "chip": (f"{hi(n['data'])} high", "bad") if hi(n["data"]) else None,
         "foot": "Gaps in the data that limit what can be measured."},
    ])
    if not items:
        _method(report, unavailable, reused)
        return

    # ---- top priorities
    urgent = [(i, p) for i, p in items if i.severity in ("high", "medium")]
    top = [x for x in urgent if x[1].kind in ("risk", "opportunity")][:MAX_TOP]            # risks and levers first,
    top += [x for x in urgent if x not in top and (x[1].kind != "data" or x[0].severity == "high")][:MAX_TOP - len(top)]
    top.sort(key=lambda x: items.index(x))                                                   # then patterns, in rank order
    if top:
        section("Top priorities", "Where to start, with the steps to take")
        for n_, (i, p) in enumerate(top, 1):
            _priority_card(n_, i, p, related_driver(i, report.insights))

    # ---- action plan
    section("Action plan", "Every recommended step in priority order")
    _action_plan(items)

    # ---- all findings
    section("All findings", f"{len(items)} in total, highest priority first")
    counts = {k: len(items) if k == "all" else len(n[k]) for k in _FILTERS}
    pick = st.segmented_control("Show", [k for k in _FILTERS if counts[k]], key="ins_filter", default="all",
                                format_func=lambda k: f"{_FILTERS[k]} ({counts[k]})", label_visibility="collapsed") or "all"
    shown = [(i, p) for i, p in items if pick == "all" or p.kind == pick]
    for k, (i, p) in enumerate(shown):
        _finding_card(k, i, p, related_driver(i, report.insights))
    _method(report, unavailable, reused)


def _chips(i: Insight, p: Plan) -> str:
    sev, tone = _SEV[i.severity]
    return (f'<span class="chip {_KIND_TONE[p.kind]}">{escape(KINDS[p.kind])}</span>'
            f'<span class="chip {tone}">{escape(sev)}</span><span>{escape(i.group)}</span>'
            f'<span>· {escape(i.confidence)} confidence</span>')


def _steps_html(p: Plan) -> str:
    if not p.steps:
        return ""
    return '<ol class="ins-steps">' + "".join(f"<li>{escape(s)}</li>" for s in p.steps) + "</ol>"


def _open_button(p: Plan, key: str) -> None:
    if p.page and p.page in PAGE_LABELS:
        if st.button(f"Open {PAGE_LABELS[p.page]}", key=key, icon=":material/arrow_forward:", type="tertiary"):
            nav.go(p.page)


def _priority_card(n: int, i: Insight, p: Plan, rel: Insight | None) -> None:
    with st.container(border=True, key=f"ins_card_{p.kind}_top{n}"):
        left, right = st.columns([1.15, 1], gap="large")
        with left:
            clue = (f'<div class="ins-clue"><b>Clue from Drivers</b>{escape(rel.description)}</div>' if rel else "")
            st.markdown(f'<div class="ins-head"><span class="ins-n">{n}</span>{_chips(i, p)}</div>'
                        f'<div class="ins-title">{escape(i.title)}</div><div class="ins-desc">{escape(i.description)}</div>'
                        + (f'<div class="ins-k">Why it matters</div><div class="ins-why">{escape(p.why)}</div>' if p.why else "")
                        + clue, unsafe_allow_html=True)
        with right:
            st.markdown(f'<div class="ins-k" style="margin-top:.1rem">What to do</div><div class="ins-do">{escape(p.action)}</div>'
                        f'{_steps_html(p)}', unsafe_allow_html=True)
            _open_button(p, f"ins_open_top{n}")


def _evidence(i: Insight) -> None:
    rows = []
    for e in i.evidence:
        name = e.metric.replace("_", " ")
        rows.append({"Measure": name[:1].upper() + name[1:], "Value": e.value, "How it is calculated": e.detail,
                     "Columns": ", ".join(e.columns), "Period": e.period})
    t = pd.DataFrame(rows)
    st.dataframe(t.loc[:, [c for c in t.columns if t[c].astype(str).str.len().gt(0).any()]], hide_index=True)
    if i.thresholds:
        st.caption(f"**When this is reported:** {i.thresholds}")
    if i.limitations:
        st.caption("**Keep in mind:** " + " ".join(dict.fromkeys(i.limitations)))


def _finding_card(k: int, i: Insight, p: Plan, rel: Insight | None) -> None:
    with st.container(border=True, key=f"ins_card_{p.kind}_{k}"):
        clue = (f'<div class="ins-clue"><b>Clue from Drivers</b>{escape(rel.description)}</div>' if rel else "")
        st.markdown(f'<div class="ins-head">{_chips(i, p)}</div><div class="ins-title sm">{escape(i.title)}</div>'
                    f'<div class="ins-desc">{escape(i.description)}</div>'
                    + (f'<div class="ins-why"><b>Why it matters.</b> {escape(p.why)}</div>' if p.why else "") + clue
                    + f'<div class="ins-k">What to do</div><div class="ins-do" style="font-size:.88rem">{escape(p.action)}</div>'
                    + _steps_html(p), unsafe_allow_html=True)
        c1, c2 = st.columns([1, 3], vertical_alignment="center")
        with c1:
            _open_button(p, f"ins_open_{k}")
        with c2.expander("Evidence and how we know"):
            _evidence(i)


def _action_plan(items: list[tuple[Insight, Plan]]) -> None:
    rows = ['<div class="plan-row head"><span></span><span>Action</span><span>Why</span><span>Priority</span></div>']
    lines = ["# Action plan", ""]
    for n, (i, p) in enumerate(items, 1):
        sev, tone = _SEV[i.severity]
        where = f" · {PAGE_LABELS[p.page]}" if p.page in PAGE_LABELS else ""
        rows.append(f'<div class="plan-row"><span class="plan-box"></span><div><div class="plan-a">{escape(p.action)}</div>'
                    f'<div class="plan-f">{escape(i.title)}{escape(where)}</div></div>'
                    f'<div class="plan-w">{escape(p.why or i.description)}</div>'
                    f'<div><span class="chip {tone}">{escape(sev.replace(" priority", ""))}</span></div></div>')
        lines += [f"{n}. **{p.action}** ({sev.lower()})", f"   - Finding: {i.title}"]
        if p.why:
            lines.append(f"   - Why: {p.why}")
        lines += [f"   - Step: {s}" for s in p.steps]
        lines.append("")
    st.html('<div class="plan">' + "".join(rows) + "</div>")
    st.download_button("Download action plan", "\n".join(lines).encode("utf-8"), file_name="action_plan.md",
                       mime="text/markdown", key="ins_plan_dl", icon=":material/download:")


def _method(report, unavailable: list[tuple[str, str]], reused: list[str]) -> None:
    with st.expander("How these insights are made"):
        st.markdown("Every finding comes from a fixed rule applied to numbers computed from your data; nothing is written by "
                    "a language model, and the same data always gives the same findings. Each finding lists its evidence, "
                    "the threshold it crossed and its limits. Thresholds are this app's adjustable reference levels, not "
                    "industry standards, and drivers show association, not cause.")
        st.markdown("**Order:** priority = 10 x severity (high 3, medium 2, low 1, info 0) + confidence (high 3, medium 2, "
                    "low 1). Confidence for KPI findings reflects how many rows were analysed.")
        if reused:
            st.markdown("**Your settings were used for:** " + ", ".join(PAGE_NAMES[r] for r in reused)
                        + ". The other analyses ran with default settings.")
        if unavailable:
            st.markdown("**Analyses that could not run:**")
            st.dataframe(pd.DataFrame([(STEP_LABEL.get(a, a), w) for a, w in unavailable], columns=["Analysis", "Why"]),
                         hide_index=True)
        if report.skipped:
            st.markdown("**Rules that did not run:**")
            st.dataframe(pd.DataFrame(report.skipped, columns=["Rule", "Why it did not run"]), hide_index=True)
